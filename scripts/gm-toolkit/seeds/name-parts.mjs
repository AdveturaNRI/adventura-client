/**
 * Слоговые конструкторы имён для рас без больших готовых списков (pynames).
 * На выходе — сотни уникальных RU-имён, чтобы генератор не крутил одни и те же 25.
 */

function uniq(arr) {
  return [...new Set(arr.filter((x) => typeof x === 'string' && x.trim()))];
}

function titleCaseRu(s) {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Декартово произведение с лимитом (не взрываем память).
 * parts: string[][]
 */
export function combineParts(parts, { max = 400, joiner = '' } = {}) {
  if (!parts.length) return [];
  let acc = [''];
  for (const pool of parts) {
    const next = [];
    for (const left of acc) {
      for (const right of pool) {
        next.push(left + joiner + right);
        if (next.length >= max * 3) break;
      }
      if (next.length >= max * 3) break;
    }
    acc = next;
  }
  // перемешиваем детерминированно по длине/хэшу строки, берём max
  const scored = uniq(acc.map((s) => titleCaseRu(s.replace(/'+/g, "'").replace(/\s+/g, ' ').trim())))
    .filter((n) => n.length >= 3 && n.length <= 28)
    .sort((a, b) => {
      const ha = [...a].reduce((h, c) => h + c.charCodeAt(0), 0);
      const hb = [...b].reduce((h, c) => h + c.charCodeAt(0), 0);
      return (ha % 97) - (hb % 97) || a.localeCompare(b, 'ru');
    });
  return scored.slice(0, max);
}

function clanCombine(adjList, nounList, max = 80, { maxPerToken = 2 } = {}) {
  /** Существительные на -ь женского рода (остальные на -ь — мужские: лебедь, олень). */
  const FEM_SOFT = new Set([
    'тень', 'ночь', 'рожь', 'мышь', 'грязь', 'кровь', 'дверь', 'площадь', 'площадь',
    'ветвь', 'рукоять', 'смерть', 'часть', 'сеть', 'цепь', 'соль', 'пыль', 'медь',
    'помощь', 'ярость', 'страсть', 'власть', 'совесть', 'печать', 'гавань', 'ступень',
  ]);

  const agreeAdj = (adj, noun) => {
    const n = noun.toLowerCase();
    let fem = false;
    let neut = false;
    if (/[ое]$/u.test(n) || /мя$/u.test(n)) {
      neut = true;
    } else if (/ь$/u.test(n)) {
      fem = FEM_SOFT.has(n);
    } else if (/[ая]$/u.test(n)) {
      fem = true;
    }
    // мужской — без изменений
    if (!fem && !neut) return adj;
    return adj
      .replace(/ный$/u, fem ? 'ная' : 'ное')
      .replace(/ний$/u, fem ? 'няя' : 'нее')
      .replace(/ый$/u, fem ? 'ая' : 'ое')
      .replace(/ий$/u, fem ? 'яя' : 'ее')
      .replace(/ой$/u, fem ? 'ая' : 'ое');
  };

  const pairs = [];
  for (const adj of adjList) {
    for (const noun of nounList) {
      pairs.push([adj, noun]);
    }
  }
  pairs.sort((a, b) => {
    const ha = [...a.join()].reduce((h, c) => h + c.charCodeAt(0), 0);
    const hb = [...b.join()].reduce((h, c) => h + c.charCodeAt(0), 0);
    return (ha % 131) - (hb % 131) || a[0].localeCompare(b[0], 'ru');
  });

  const adjCount = new Map();
  const nounCount = new Map();
  const out = [];
  for (const [adj, noun] of pairs) {
    if ((adjCount.get(adj) || 0) >= maxPerToken) continue;
    if ((nounCount.get(noun) || 0) >= maxPerToken) continue;
    out.push(`${agreeAdj(adj, noun)} ${noun}`);
    adjCount.set(adj, (adjCount.get(adj) || 0) + 1);
    nounCount.set(noun, (nounCount.get(noun) || 0) + 1);
    if (out.length >= max) break;
  }
  return uniq(out);
}

