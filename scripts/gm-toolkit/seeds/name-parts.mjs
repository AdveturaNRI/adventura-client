/**
 * Добивает фамилии/кланы, если их мало (эльфы с 5 фамилиями тоже зацикливаются).
 */
export function padSurnamesAndClans(raceKey, { surnames = [], clans = [] } = {}) {
  const family = raceKey.startsWith('elf')
    ? 'elf'
    : raceKey === 'orc'
      ? 'orc'
      : /goblin|hobgoblin|bugbear|kobold/.test(raceKey)
        ? 'goblin'
        : raceKey.startsWith('dwarf')
          ? 'dwarf'
          : raceKey === 'gnome_rock' || raceKey === 'gnome_forest'
            ? raceKey
            : null;

  if (!family || !NAME_PARTS[family]) {
    return { surnames: uniq(surnames), clans: uniq(clans) };
  }
  const parts = NAME_PARTS[family];
  let nextSurnames = uniq(surnames);
  let nextClans = uniq(clans);

  if (nextSurnames.length < 40 && parts.surnames?.length) {
    nextSurnames = uniq([...nextSurnames, ...parts.surnames]);
  }
  if (nextSurnames.length < 80 && parts.surnamesAdj && parts.surnamesNoun) {
    nextSurnames = uniq([
      ...nextSurnames,
      ...clanCombine(parts.surnamesAdj, parts.surnamesNoun, 120, { maxPerToken: 2 }),
    ]);
  }
  if (nextClans.length < 80 && parts.clansAdj && parts.clansNoun) {
    nextClans = uniq([
      ...nextClans,
      ...clanCombine(parts.clansAdj, parts.clansNoun, 100, { maxPerToken: 2 }),
    ]);
  }

  return {
    surnames: nextSurnames.length ? nextSurnames : undefined,
    clans: nextClans.length ? nextClans : undefined,
  };
}

/**
 * Расширяет пул имён расы до target на пол, сохраняя seed-имена первыми.
 */
export function expandRaceNames(raceKey, seedNames, { target = 160 } = {}) {
  const family =
    raceKey.startsWith('dwarf')
      ? 'dwarf'
      : raceKey === 'gnome_rock' || raceKey === 'gnome_forest'
        ? raceKey
        : raceKey.startsWith('human_celtic')
          ? 'human_celtic'
          : raceKey.startsWith('human_arabic')
            ? 'human_arabic'
            : raceKey.startsWith('human_greek')
              ? 'human_greek'
              : raceKey in NAME_PARTS
                ? raceKey
                : null;

  if (!family || !NAME_PARTS[family]) {
    return {
      m: uniq(seedNames.m),
      f: uniq(seedNames.f),
      expanded: false,
    };
  }

  const parts = NAME_PARTS[family];
  const genGender = (gender) => {
    const seed = seedNames[gender] || [];
    if (seed.length >= target) return uniq(seed);
    const p = parts[gender];
    if (!p) return uniq(seed);

    let generated;
    if (p.middles) {
      generated = combineParts([p.prefixes, p.middles, p.suffixes], {
        max: target * 2,
      });
    } else {
      generated = combineParts([p.prefixes, p.suffixes], { max: target * 2 });
    }

    // фильтр: мужские не на -а/-я (кроме исключений), женские — чаще на гласную
    const filtered = generated.filter((n) => {
      const lower = n.toLowerCase();
      if (gender === 'm' && /[ая]$/u.test(lower) && !/^(никита|илья)$/u.test(lower)) {
        return false;
      }
      if (n.length < 3) return false;
      return true;
    });

    return uniq([...seed, ...filtered]).slice(0, Math.max(target, seed.length));
  };

  return {
    m: genGender('m'),
    f: genGender('f'),
    expanded: true,
    family,
    clans: parts.clansAdj && parts.clansNoun
      ? clanCombine(parts.clansAdj, parts.clansNoun, 60)
      : parts.clans || undefined,
    surnames:
      parts.surnames ||
      (parts.surnamesAdj && parts.surnamesNoun
        ? clanCombine(parts.surnamesAdj, parts.surnamesNoun, 50)
        : undefined),
  };
}
